# SECURITY WARNING: keep the secret key used in production secret!
def _carregar_secret_key():
    """Lê a chave de DJANGO_SECRET_KEY; em desenvolvimento, gera uma vez e guarda em
    .secret_key (arquivo ignorado pelo git). Nenhuma chave fica no código-fonte."""
    chave = os.environ.get("DJANGO_SECRET_KEY")
    if chave:
        return chave
    arquivo = BASE_DIR / ".secret_key"
    if not arquivo.exists():
        from django.core.management.utils import get_random_secret_key
        arquivo.write_text(get_random_secret_key(), encoding="utf-8")
        arquivo.chmod(0o600)
    return arquivo.read_text(encoding="utf-8").strip()


