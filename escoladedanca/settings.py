AUDITORIA_DIAS_RETENCAO = int(os.environ.get("AUDITORIA_DIAS_RETENCAO", "180"))


def _arquivo_de_log(nome):
    if EM_TESTE:  # a suíte de testes não escreve no log real
        return {"class": "logging.NullHandler"}
    return {
        "class": "logging.handlers.TimedRotatingFileHandler",
        "filename": LOGS_DIR / nome,
        "when": "midnight",
        "backupCount": AUDITORIA_DIAS_RETENCAO,
        "encoding": "utf-8",
        "formatter": "auditoria",
    }


